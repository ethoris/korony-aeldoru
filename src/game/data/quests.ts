// docs/gdd/06-zadania.md – zadania rozdziałów I–VI (krainy 1–6, poz. 1–120).
//
// Uproszczenia względem tekstu GDD (scenki z wyborem nie mają tu gałęzi):
// - liczniki "wygranych" są liczone dla CAŁEJ lokacji, nie dla konkretnego
//   gatunku potwora (GDD czasem podaje "5 pająków" – u nas to "5 wygranych
//   w tej lokacji");
// - scenki z wyborem (np. "zabij / śledź / przekup") nie mają gałęzi – zadanie
//   zalicza się na tych samych warunkach, nagroda jak w tabeli bez wariantu;
//   gdy GDD nie podaje liczby wygranych dla scenki, przyjmujemy rozsądną
//   wartość (3–10, zależnie od poziomu lokacji) – to jest wymyślone przez nas,
//   nie z GDD;
// - "nagrody specjalne" zlecenia, które wymagają jeszcze nieistniejących
//   systemów (sklep, kuźnia/runy, twierdza/produkcja, odporności z ekwipunku)
//   są zapisywane jako informacja, ale nie mają jeszcze mechanicznego efektu
//   – patrz `special.active`;
// - zakończenie sagi (rozdział VI: zniszczyć czy założyć koronę) nie ma
//   wyboru w grze – zawsze rozlicza się jako "zniszczenie korony" (tytuł
//   „Łamacz Korony”), prostsze zakończenie bez dodatkowych skutków;
// - "wybór rzadkiego/legendarnego przedmiotu" w zleceniach (nie w finałach
//   rozdziału, te dostają przedmiot przez `grantsStoryItem`) nie jest jeszcze
//   mechanicznie wspierany – gracz nie dostaje z tego dodatkowego przedmiotu.
export type QuestConditionType = "WIN_COUNT" | "DEEP_WIN" | "BOSS_DEFEAT" | "FIND_ITEM";

export interface QuestCondition {
  type: QuestConditionType;
  target?: number;
  chance?: number;
  bossKey?: string;
}

export type SpecialRewardKey =
  | "STAMINA_30"
  | "BLESSING"
  | "SHORTCUT"
  | "TREASURE_MAP"
  | "DISCOUNT"
  | "GOLD_BONUS"
  | "FREE_RUNE"
  | "PRODUCTION_BONUS"
  | "RESIST_BONUS"
  | "RARE_ITEM_CHOICE";

export interface QuestDefinition {
  key: string;
  chapter: 1 | 2 | 3 | 4 | 5 | 6;
  locationKey: string;
  kind: "STORY" | "COMMISSION";
  title: string;
  summary: string;
  condition: QuestCondition;
  isChapterFinale?: boolean;
  /** Tylko dla zadań fabularnych: co drugie daje przedmiot dla klasy gracza. */
  storyOrder?: number;
  special?: { key: SpecialRewardKey; label: string; active: boolean; amount?: number };
  /** Tytuł przyznawany za to zadanie (poza standardową nagrodą finału rozdziału). */
  titleReward?: { key: string; name: string };
}

